function spec = background_spec_(obj)
% spec = background_spec_(obj)
% The active combination's background as plain values: what
% stimgen.util.background_source builds from.
%
% Every value is read through active_value_, so a vectorized background
% property reports the combination that produced the current Signal and the
% variant selection is not advanced.
%
% Returns:
%   spec - struct: Type, Level, HighPass, LowPass, Frequency, LoopDuration,
%          Seed, Fs, ApplyCalibration
spec = struct( ...
    'Type',             string(obj.Background), ...
    'Level',            double(obj.background_level_()), ...
    'HighPass',         double(obj.active_value_("BackgroundHighPass")), ...
    'LowPass',          double(obj.active_value_("BackgroundLowPass")), ...
    'Frequency',        double(obj.active_value_("BackgroundFrequency")), ...
    'LoopDuration',     double(obj.BackgroundLoopDuration), ...
    'Seed',             double(obj.BackgroundSeed), ...
    'Fs',               double(obj.Fs), ...
    'ApplyCalibration', logical(obj.ApplyCalibration));
end
